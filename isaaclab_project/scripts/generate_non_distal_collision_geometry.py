"""Bake exact per-collider CAD hull witnesses for joint/body ground clearance.

Run with a Python environment containing NumPy and SciPy. The generated module
needs neither dependency at runtime. This reads the normalized training URDF
and its original binary STL meshes; it does not launch Isaac Sim or edit assets.
"""

from __future__ import annotations

import argparse
import hashlib
import math
from pathlib import Path
import pprint
import struct
import xml.etree.ElementTree as ET


PROJECT = Path(__file__).resolve().parents[1]
ASSET_DIR = PROJECT / "assets/spiderbot_variants/onshape_20260928"
DEFAULT_OUTPUT = PROJECT / "source/dksh_isaaclab/dksh_isaaclab/tasks/direct/spider_navigation/joint_angle_non_distal_geometry.py"
EXCLUDED_FOOT_MESH = "assets/part_1__8.stl"


def stl_points(path):
    """Return every unique float32 triangle vertex in a binary STL."""
    data = Path(path).read_bytes()
    count = struct.unpack_from("<I", data, 80)[0]
    if len(data) != 84 + 50 * count:
        raise ValueError(f"Expected a complete binary STL: {path}")
    return tuple(sorted({struct.unpack_from("<fff", data, 84 + 50 * index + offset)
                         for index in range(count) for offset in (12, 24, 36)}))


def collision_transform(collision):
    """URDF mesh-to-LINK affine transform, including nonuniform mesh scale."""
    element = collision.find("origin")
    xyz = (0.0, 0.0, 0.0) if element is None else tuple(map(float, element.get("xyz", "0 0 0").split()))
    rpy = (0.0, 0.0, 0.0) if element is None else tuple(map(float, element.get("rpy", "0 0 0").split()))
    roll, pitch, yaw = rpy
    sr, cr = math.sin(roll), math.cos(roll)
    sp, cp = math.sin(pitch), math.cos(pitch)
    sy, cy = math.sin(yaw), math.cos(yaw)
    rotation = ((cy*cp, cy*sp*sr - sy*cr, cy*sp*cr + sy*sr),
                (sy*cp, sy*sp*sr + cy*cr, sy*sp*cr - cy*sr),
                (-sp, cp*sr, cp*cr))
    scale = tuple(map(float, collision.find("geometry/mesh").get("scale", "1 1 1").split()))
    return tuple(tuple(rotation[i][j] * scale[j] for j in range(3)) + (xyz[i],)
                 for i in range(3))


def source_collisions(asset_dir=ASSET_DIR):
    """Keep every base/hip/femur collider and the tibia's separate servo mesh."""
    root = ET.parse(Path(asset_dir) / "robot.training.urdf").getroot()
    expected = ["base"] + [f"leg_{leg}_{part}" for leg in range(6) for part in ("hip", "femur", "tibia")]
    bodies = {}
    for body_name in expected:
        link = root.find(f"link[@name='{body_name}']")
        if link is None:
            raise ValueError(f"Missing expected CAD body: {body_name}")
        collisions = []
        for collision in link.findall("collision"):
            mesh = collision.find("geometry/mesh")
            if mesh is None:
                raise ValueError(f"Expected a CAD mesh collider on {body_name}")
            filename = mesh.get("filename")
            if body_name.endswith("_tibia") and filename == EXCLUDED_FOOT_MESH:
                continue
            collisions.append((filename, collision_transform(collision)))
        if not collisions:
            raise ValueError(f"No non-distal collision geometry on {body_name}")
        bodies[body_name] = tuple(collisions)
    return bodies


def render_module(asset_dir=ASSET_DIR):
    import numpy as np
    from scipy.spatial import ConvexHull

    asset_dir = Path(asset_dir)
    bodies = source_collisions(asset_dir)
    mesh_names = sorted({filename for collisions in bodies.values() for filename, _ in collisions})
    meshes, hashes = {}, {}
    for filename in mesh_names:
        path = asset_dir / filename
        raw = np.asarray(stl_points(path), dtype=float)
        meshes[filename] = tuple(sorted(tuple(float(value) for value in point)
                                        for point in raw[ConvexHull(raw).vertices]))
        hashes[filename] = hashlib.sha256(path.read_bytes()).hexdigest()
    urdf_hash = hashlib.sha256((asset_dir / "robot.training.urdf").read_bytes()).hexdigest()
    usd_hash = hashlib.sha256((asset_dir / "onshape_20260928.usd").read_bytes()).hexdigest()
    pretty = lambda value: pprint.pformat(value, width=110, sort_dicts=False)
    return f'''"""Exact CAD collision witnesses for body, hip, femur and tibia-servo clearance.

Generated by scripts/generate_non_distal_collision_geometry.py from the actual
normalized URDF and binary STL collision meshes, in each rigid body's LINK frame.
Source URDF SHA256: {urdf_hash}
Corresponding USD SHA256: {usd_hash}

Each collider retains its own exact convex hull before its URDF affine transform.
Their union preserves separate collision pieces; no combined-link hull or hull
simplification is used. The fixed foot (part_1__8.stl) is deliberately excluded:
joint_angle_foot_geometry.py owns its distal/non-distal contact contract.

Runtime uses only Python constants and builtins, with no asset access, NumPy,
SciPy or USD imports. Vertex sampling is a clearance estimate near terrain edges.
"""

from __future__ import annotations


ONSHAPE_NON_DISTAL_COLLISION_URDF_SHA256 = {urdf_hash!r}
ONSHAPE_NON_DISTAL_COLLISION_USD_SHA256 = {usd_hash!r}
ONSHAPE_NON_DISTAL_COLLISION_MESH_SHA256 = {pretty(hashes)}

# Unique source-mesh hulls in metres, before the URDF affine transforms.
_MESH_HULL_POINTS_M = {pretty(meshes)}

# body -> ((mesh filename, 3x4 mesh-to-LINK affine transform), ...).
_BODY_COLLISIONS = {pretty(bodies)}


def _link_offsets(collisions):
    return tuple(sorted({{
        tuple(sum(matrix[i][j] * point[j] for j in range(3)) + matrix[i][3]
              for i in range(3))
        for filename, matrix in collisions for point in _MESH_HULL_POINTS_M[filename]
    }}))


# Public mapping: body name -> nonempty tuple of 3-D points in that LINK frame.
# base + six hips + six femurs + six tibia servo colliders; no foot witnesses.
ONSHAPE_NON_DISTAL_COLLISION_OFFSETS = {{
    body: _link_offsets(collisions) for body, collisions in _BODY_COLLISIONS.items()
}}
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--asset-dir", type=Path, default=ASSET_DIR)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true", help="Fail if the saved generated module differs")
    args = parser.parse_args()
    source = render_module(args.asset_dir)
    if args.check:
        if args.output.read_text(encoding="utf-8") != source:
            parser.exit(1, "Non-distal collision geometry is stale; regenerate it.\n")
    else:
        args.output.write_text(source, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
